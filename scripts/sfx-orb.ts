// Renders the intro's sound effects (web/orb/sfx/sfx.json) with ElevenLabs sound generation.
// An effect is rendered once per prompt+length; edited effects replace their old file.
// Writes manifest.js, which the page loads with a plain <script> so it also works from disk.
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const DIR = "web/orb/sfx";
const key = process.env.ELEVENLABS_API_KEY;

type Effect = { prompt: string; seconds: number };

async function render(e: Effect): Promise<Buffer | null> {
  if (!key) return null;
  const res = await fetch("https://api.elevenlabs.io/v1/sound-generation?output_format=mp3_44100_128", {
    method: "POST",
    headers: { "xi-api-key": key, "Content-Type": "application/json" },
    body: JSON.stringify({ text: e.prompt, duration_seconds: e.seconds, prompt_influence: 0.5 }),
  }).catch(() => null);
  if (!res?.ok) {
    console.error("render failed", res?.status, await res?.text().catch(() => ""));
    return null;
  }
  return Buffer.from(await res.arrayBuffer());
}

const effects: Record<string, Effect> = JSON.parse(readFileSync(join(DIR, "sfx.json"), "utf8"));
const manifest: Record<string, string | null> = {};

for (const [id, e] of Object.entries(effects)) {
  const file = `${id}-${createHash("sha1").update(`${e.prompt}|${e.seconds}`).digest("hex").slice(0, 10)}.mp3`;
  if (!existsSync(join(DIR, file))) {
    const audio = await render(e);
    if (!audio) {
      manifest[id] = null;
      continue;
    }
    writeFileSync(join(DIR, file), audio);
    console.log("rendered", id);
  }
  manifest[id] = file;
  for (const f of readdirSync(DIR)) {
    if (f.startsWith(`${id}-`) && f !== file) unlinkSync(join(DIR, f));
  }
}

writeFileSync(join(DIR, "manifest.js"), `// Generated by scripts/sfx-orb.ts from sfx.json. Do not edit.\nwindow.ORB_SFX = ${JSON.stringify(manifest, null, 1)};\n`);
console.log(`manifest: ${Object.values(manifest).filter(Boolean).length}/${Object.keys(manifest).length} effects`);
