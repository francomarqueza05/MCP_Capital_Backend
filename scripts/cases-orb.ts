// Pulls every case from the Sherpas MCP, runs the summary detector on it and writes
// web/orb/data/cases.js for the prototype (a plain <script>, so it also works from disk).
import { mkdirSync, writeFileSync } from "node:fs";
import { detect } from "../src/scenes/detect";

const url = process.env.MCP_URL, token = process.env.MCP_TOKEN;
if (!url || !token) throw new Error("MCP_URL and MCP_TOKEN are required");

let session: string | null = null, nextId = 1;
async function rpc(method: string, params: unknown): Promise<any> {
  const res = await fetch(url!, {
    method: "POST",
    headers: { "Content-Type": "application/json", Accept: "application/json, text/event-stream", Authorization: `Bearer ${token}`, ...(session ? { "mcp-session-id": session } : {}) },
    body: JSON.stringify({ jsonrpc: "2.0", id: nextId++, method, params }),
  });
  if (!res.ok) throw new Error(`${method}: ${res.status} ${await res.text()}`);
  session = res.headers.get("mcp-session-id") ?? session;
  const text = await res.text(), line = text.split("\n").find((l) => l.startsWith("data:"));
  return JSON.parse(line ? line.slice(5) : text);
}
const tool = async (name: string, args: Record<string, string>) =>
  (await rpc("tools/call", { name, arguments: args })).result.content.map((c: any) => c.text).join("\n");

await rpc("initialize", { protocolVersion: "2025-03-26", capabilities: {}, clientInfo: { name: "cordada", version: "0.1" } });
const cases: { id: string }[] = JSON.parse(await tool("list_cases", {}));
const out: Record<string, unknown> = {};
for (const { id } of cases) {
  const fh = JSON.parse(await tool("get_case", { caseId: id, part: "financial-health" }));
  const ia = JSON.parse(await tool("get_case", { caseId: id, part: "investment-analysis" }));
  out[id] = detect(fh, ia);
  console.log(id, (out[id] as any).topics.map((t: any) => `${t.id}:${t.status}`).join(" "));
}
mkdirSync("web/orb/data", { recursive: true });
writeFileSync("web/orb/data/cases.js", `// Generated by scripts/cases-orb.ts from the Sherpas MCP. Do not edit.\nwindow.ORB_CASES = ${JSON.stringify(out, null, 1)};\n`);
